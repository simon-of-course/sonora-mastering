inline VSTGUI::CView* createMasterView(VSTGUI::UTF8StringPtr name, const VSTGUI::UIAttributes& a,
                                       const VSTGUI::IUIDescription* d, VSTGUI::VST3Editor*,
                                       MasterUiContext& ctx) {
    if (auto* v = detail::createCommonView(name, a, d, ctx)) return v;
    if (!name) return nullptr;
    CRect rect;
    detail::readRect(a, rect);
    const std::string n(name);
    if (n == "SonoraEqGraph") return new EqGraph(rect, &ctx, detail::Fonts(d));
    if (n == "SonoraEqFader") {
        auto* f = new EqFader(rect);
        f->setAccent(detail::readColor(a, d, "sonora-accent", theme::accent));
        return f;
    }
    if (n == "SonoraAnalysisStatus") return new AnalysisStatus(rect, &ctx, detail::Fonts(d));
    if (n == "SonoraLevelMeters") return new LevelMeters(rect, &ctx, detail::Fonts(d));
    if (n == "SonoraGainReduction") return new GainReduction(rect, &ctx, detail::Fonts(d));
    if (n == "SonoraLoudness") return new Loudness(rect, &ctx, detail::Fonts(d));
    if (n == "SonoraCorrelation") return new Correlation(rect, &ctx, detail::Fonts(d));
    return nullptr;
}

inline VSTGUI::CView* createShutterView(VSTGUI::UTF8StringPtr name, const VSTGUI::UIAttributes& a,
                                        const VSTGUI::IUIDescription* d, VSTGUI::VST3Editor*,
                                        ShutterUiContext& ctx) {
    if (auto* v = detail::createCommonView(name, a, d, ctx)) return v;
    if (name && std::strcmp(name, "SonoraShutterScope") == 0) {
        CRect rect;
        detail::readRect(a, rect);
        return new ShutterScope(rect, &ctx, detail::Fonts(d));
    }
    return nullptr;
}

