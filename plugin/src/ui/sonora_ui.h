using VSTGUI::SharedPointer;

inline SharedPointer<VSTGUI::CGraphicsPath> path(VSTGUI::CDrawContext* c) {
    return VSTGUI::owned(c->createGraphicsPath());
}

inline void fillRound(VSTGUI::CDrawContext* c, const CRect& r, CCoord radius, const CColor& fill) {
    if (auto p = path(c)) {
        p->addRoundRect(r, radius);
        c->setFillColor(fill);
        c->drawGraphicsPath(p, VSTGUI::CDrawContext::kPathFilled);
    }
}

inline void strokeRound(VSTGUI::CDrawContext* c, const CRect& r, CCoord radius, const CColor& col,
                        CCoord width = 1.0) {
    if (auto p = path(c)) {
        CRect rr(r);
        rr.inset(width * 0.5, width * 0.5);
        p->addRoundRect(rr, radius);
        c->setFrameColor(col);
        c->setLineWidth(width);
        c->setLineStyle(VSTGUI::kLineSolid);
        c->drawGraphicsPath(p, VSTGUI::CDrawContext::kPathStroked);
    }
}

inline void gradientRound(VSTGUI::CDrawContext* c, const CRect& r, CCoord radius, const CColor& top,
                          const CColor& bottom) {
    auto p = path(c);
    auto g = VSTGUI::owned(VSTGUI::CGradient::create(0.0, 1.0, top, bottom));
    if (p && g) {
        p->addRoundRect(r, radius);
        c->fillLinearGradient(p, *g, CPoint(r.left, r.top), CPoint(r.left, r.bottom));
    }
}

inline void line(VSTGUI::CDrawContext* c, CPoint a, CPoint b, const CColor& col, CCoord w = 1.0) {
    c->setFrameColor(col);
    c->setLineWidth(w);
    c->setLineStyle(VSTGUI::kLineSolid);
    c->drawLine(a, b);
}

