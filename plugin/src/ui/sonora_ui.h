// SONORA shared VSTGUI views — dark premium design system for Master, Shutter and Drowner.
//
// INTEGRATION (per plugin, ~15 lines of glue):
//   1. #include "ui/sonora_ui.h" in sonora_<plugin>.cpp (include path: plugin/src).
//   2. Add members:
//        sonora::ui::MasterMeterBridge meters_;       // or ShutterMeterBridge / DrownerMeterBridge
//        sonora::ui::MasterUiContext   uiContext_;     // or ShutterUiContext / DrownerUiContext
//      and in the constructor (or initialize()):
//        uiContext_.meters = &meters_;
//        uiContext_.getParam = [this](Steinberg::Vst::ParamID id) { return getParamNormalized(id); };
//   3. Forward the VST3EditorDelegate hook:
//        VSTGUI::CView* createCustomView(VSTGUI::UTF8StringPtr name, const VSTGUI::UIAttributes& a,
//                                         const VSTGUI::IUIDescription* d, VSTGUI::VST3Editor* e) override
//        { return sonora::ui::createMasterView(name, a, d, e, uiContext_); }
//   4. Audio thread: publish meters once per block (see meter_bridge.h). Master:
//        if (meters_.consumeLoudnessResetRequest()) engine_.resetLoudness();
//        engine_.process(...);
//        meters_.publish(engine_.meters());      // copies the whole master::MasterMeters snapshot
//        meters_.publishSampleRate(sampleRate);  // once in setupProcessing() is enough
//      (granular publishLevels / publishLoudness / ... calls exist as well.)
//      Shutter: meters_.publish(gainL, gainR, phase01, enabled, playing) where
//        phase01 = fmod(ProcessContext::projectTimeMusic, 8.0) / 8.0 (position in the 2-bar scope
//        window; free-rate mode: fmod(cycles, 8) / 8). Drowner: meters_.publish(depth, cutoffHz).
//      If the plugin is a split processor/controller, the bridge must live where both can reach
//      it (same-process singleton keyed by an instance id sent via IMessage), never via params.
//   5. Parameter strings: the CParamDisplay value texts are produced by
//      EditController::getParamStringByValue -> Parameter::toString (verified in
//      vstgui4/vstgui/plugin-bindings/vst3editor.cpp, ParameterChangeListener::convertValueToString,
//      UTF-8 safe). Plain RangeParameter prints no unit, so register parameters with
//      sonora::ui::FormattedParameter (ui/param_format.h) to get "+1,5 dB", "50 %", "Aus", ...
//      e.g. parameters.addParameter(new sonora::ui::FormattedParameter(
//               STR16("Bass"), 2, -6.0, 6.0, 0.0, sonora::ui::ParamFormat::db(1, true)));
//      Drowner "Abtauchzeit" (id 2) is logarithmic: ParamFormat::seconds(2).withLog().
//      List parameters (Bus-Modus, Preset, Notenwert, Form, Stereo, Gate-Klang) must be
//      StringListParameter: VST3Editor fills COptionMenu / CSegmentButton entries from them.
//   6. Layout: plugin/resource/*.uidesc and the website previews *-preview.html are GENERATED by
//      plugin/src/ui/tools/gen_ui.py (single layout source) - edit the script, then re-run it.
//      Editor sizes: Master 960x640, Shutter 640x420, Drowner 640x420 (template name "view").
//
// Everything else is automatic:
//   * All controls are bound by control-tag in the .uidesc (VST3Editor binds them to parameters,
//     sets default values => Ctrl/Cmd-click and double-click reset to the parameter default).
//   * Views that depend on several parameters (EQ graph, shutter scope, water view, mode-dependent
//     dimming) poll the normalized values through UiContext::getParam in onIdle() with change
//     detection, so no listener registration / notify calls are needed. If getParam is empty the
//     views fall back to sensible defaults (and EqGraph::setBandGains can be called manually).
//   * Mode / state dependent sections: containers with custom-view-name="SonoraCard" and the
//     attribute sonora-active-when="<paramId>=<index,index>" (+ sonora-steps="<stepCount>") dim
//     themselves (alpha 0.3) and ignore the mouse while the condition is false. The named
//     containers (name="...") are listed in the uidesc comments, so a glue may also use
//     verifyView() to find and show/hide them if a different behaviour is wanted.
//   * All views are safe with a null bridge (meters show "--", status shows a hint).
//   * Without the delegate forwarding, every custom view degrades to its base VSTGUI class
//     (class="..." attribute in the uidesc), so the editor still opens and works.
//
// Custom view names: SonoraRoot, SonoraCard, SonoraKnob, SonoraToggle, SonoraSegment, SonoraMenu,
//   SonoraEqGraph, SonoraEqFader, SonoraAnalysisStatus, SonoraLevelMeters, SonoraGainReduction,
//   SonoraLoudness, SonoraCorrelation (Master), SonoraShutterScope (Shutter), SonoraWaterView
//   (Drowner).
