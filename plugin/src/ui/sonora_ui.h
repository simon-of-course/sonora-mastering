inline Card::Style cardStyle(const std::string& s) {
    if (s == "root") return Card::Style::Root;
    if (s == "header") return Card::Style::Header;
    if (s == "inset") return Card::Style::Inset;
    if (s == "none") return Card::Style::None;
    return Card::Style::Card;
}

// Shared controls for all plugins. Returns nullptr for unknown names.
inline VSTGUI::CView* createCommonView(VSTGUI::UTF8StringPtr name, const VSTGUI::UIAttributes& a,
                                       const VSTGUI::IUIDescription* d, const UiContext& ctx) {
    if (!name) return nullptr;
    CRect rect;
    readRect(a, rect); // final size/origin is (re)applied by the uidesc "class" attributes
    const std::string n(name);
    if (n == "SonoraRoot" || n == "SonoraCard") {
        auto* card = new Card(rect, n == "SonoraRoot" ? Card::Style::Root : cardStyle(attr(a, "sonora-style", "card")),
                              &ctx, Fonts(d));
        card->setTitle(attr(a, "sonora-title"));
        card->setAccent(readColor(a, d, "sonora-accent", theme::accent));
        const auto rule = attr(a, "sonora-active-when");
        if (!rule.empty())
            card->setRule(ActiveRule::parse(rule, std::atoi(attr(a, "sonora-steps", "1").c_str())));
        return card;
    }
    if (n == "SonoraKnob") return new ArcKnob(rect);
    if (n == "SonoraToggle") {
        auto* t = new Toggle(rect, Fonts(d));
        t->setOnColor(readColor(a, d, "sonora-on-color", theme::accent));
        t->setBig(attr(a, "sonora-big") == "true");
        t->setMomentary(attr(a, "sonora-momentary") == "true");
        return t;
    }
    if (n == "SonoraSegment") {
        auto* s = new Segment(rect, Fonts(d));
        s->setAccent(readColor(a, d, "sonora-accent", theme::accent));
        return s;
    }
    if (n == "SonoraMenu") return new Menu(rect, Fonts(d));
    return nullptr;
}

