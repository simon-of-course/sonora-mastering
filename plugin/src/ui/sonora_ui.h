// German number formatting ("-1,5"), optional explicit plus sign.
inline std::string num(double v, int decimals, bool plus = false) {
    char buf[48];
    if (std::abs(v) < 0.5 * std::pow(10.0, -decimals)) v = 0.0;
    std::snprintf(buf, sizeof(buf), plus ? "%+.*f" : "%.*f", decimals, v);
    std::string s(buf);
    for (auto& ch : s) if (ch == '.') ch = ',';
    if (plus && v == 0.0 && !s.empty() && s[0] == '+') s[0] = ' ', s.erase(0, 1);
    return s;
}

inline std::string attr(const VSTGUI::UIAttributes& a, const char* name, const char* def = "") {
    const auto* v = a.getAttributeValue(name);
    return v ? *v : std::string(def);
}

inline bool readRect(const VSTGUI::UIAttributes& a, CRect& rect) {
    CPoint o, s;
    if (!a.getPointAttribute("origin", o) || !a.getPointAttribute("size", s)) return false;
    rect = CRect(o.x, o.y, o.x + s.x, o.y + s.y);
    return true;
}

// "#rrggbb", "#rrggbbaa" or a named uidesc color.
inline CColor readColor(const VSTGUI::UIAttributes& a, const VSTGUI::IUIDescription* d,
                        const char* name, const CColor& fallback) {
    const auto* v = a.getAttributeValue(name);
    if (!v || v->empty()) return fallback;
    if ((*v)[0] == '#' && (v->size() == 7 || v->size() == 9)) {
        auto hex = [&](std::size_t i) {
            return static_cast<std::uint8_t>(std::strtoul(v->substr(i, 2).c_str(), nullptr, 16));
        };
        return {hex(1), hex(3), hex(5), v->size() == 9 ? hex(7) : std::uint8_t(255)};
    }
    CColor c = fallback;
    if (d && d->getColor(v->c_str(), c)) return c;
    return fallback;
}

// Fonts: prefer the named uidesc font (handles alternative-font-names), else Segoe UI.
