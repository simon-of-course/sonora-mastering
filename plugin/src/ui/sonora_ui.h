inline CColor withAlpha(CColor c, int alpha) {
    c.alpha = static_cast<std::uint8_t>(std::clamp(alpha, 0, 255));
    return c;
}
inline CColor mixColor(const CColor& a, const CColor& b, double t) {
    t = std::clamp(t, 0.0, 1.0);
    auto m = [t](std::uint8_t x, std::uint8_t y) {
        return static_cast<std::uint8_t>(std::lround(x + (y - x) * t));
    };
    return {m(a.red, b.red), m(a.green, b.green), m(a.blue, b.blue), m(a.alpha, b.alpha)};
}

