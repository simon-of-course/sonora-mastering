using ParamGetter = std::function<double(std::uint32_t /*ParamID*/)>;

struct UiContext {
    ParamGetter getParam; // normalized 0..1 values (controller side), UI thread only

    double param(std::uint32_t id, double fallback) const {
        if (!getParam) return fallback;
        const double v = getParam(id);
        return std::isfinite(v) ? std::clamp(v, 0.0, 1.0) : fallback;
    }
};

struct MasterUiContext : UiContext {
    MasterMeterBridge* meters = nullptr;
};

struct ShutterUiContext : UiContext {
    ShutterMeterBridge* meters = nullptr;
    // Optional exact gate model from the engine: gain 0..1 at musical position `beats` (quarter
    // notes from the start of the 2-bar window; free-rate mode: gate cycles) for channel 0/1,
    // using the current parameters. If empty the scope uses its built-in approximation.
    std::function<double(double beats, int channel)> gateAt;
};

