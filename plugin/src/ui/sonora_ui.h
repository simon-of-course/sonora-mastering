// "0=1,2" + steps -> condition "index of param 0 in {1,2}"
struct ActiveRule {
    int paramId = -1;
    int steps = 1;
    std::uint32_t mask = 0;
    bool valid() const { return paramId >= 0 && mask != 0; }
    bool eval(double normalized) const {
        const int idx = std::clamp(static_cast<int>(std::lround(normalized * steps)), 0, 31);
        return (mask >> idx) & 1u;
    }
    static ActiveRule parse(const std::string& spec, int steps) {
        ActiveRule r;
        const auto eq = spec.find('=');
        if (eq == std::string::npos) return r;
        r.paramId = std::atoi(spec.substr(0, eq).c_str());
        r.steps = std::max(1, steps);
        std::size_t pos = eq + 1;
        while (pos < spec.size()) {
            auto comma = spec.find(',', pos);
            if (comma == std::string::npos) comma = spec.size();
            const int idx = std::atoi(spec.substr(pos, comma - pos).c_str());
            if (idx >= 0 && idx < 32) r.mask |= (1u << idx);
            pos = comma + 1;
        }
        return r;
    }
};

inline double nowSeconds() {
    using namespace std::chrono;
    return duration<double>(steady_clock::now().time_since_epoch()).count();
}

// IEC 60268-18 style meter deflection, 0..1 for -70..0 dB.
inline double iecScale(double db) {
    double p;
    if (db < -70.0) p = 0.0;
    else if (db < -60.0) p = (db + 70.0) * 0.25;
    else if (db < -50.0) p = (db + 60.0) * 0.5 + 2.5;
    else if (db < -40.0) p = (db + 50.0) * 0.75 + 7.5;
    else if (db < -30.0) p = (db + 40.0) * 1.5 + 15.0;
    else if (db < -20.0) p = (db + 30.0) * 2.0 + 30.0;
    else if (db < 0.0) p = (db + 20.0) * 2.5 + 50.0;
    else p = 100.0;
    return p / 100.0;
}

inline double linToDb(double v) { return v > 1e-6 ? 20.0 * std::log10(v) : -120.0; }

// Magnitude (dB) of a biquad at frequency f for sample rate sr.
inline double biquadDb(const sonora::dsp::Biquad& q, double f, double sr) {
    const double w = 2.0 * sonora::dsp::kPi * f / sr;
    const std::complex<double> z1 = std::polar(1.0, -w), z2 = std::polar(1.0, -2.0 * w);
    const auto num = q.b0 + q.b1 * z1 + q.b2 * z2;
    const auto den = 1.0 + q.a1 * z1 + q.a2 * z2;
    const double mag = std::abs(num) / std::max(1e-12, std::abs(den));
    return 20.0 * std::log10(std::max(1e-9, mag));
}

